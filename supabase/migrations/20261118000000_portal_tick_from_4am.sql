-- 毎朝のポータル自動同期を 04:00 から始める（これまでは 06:00）
--
-- ポータルは短い時間に何度もログインすると受け付けなくなる（4〜5 社続けると止められる）。
-- そこで会社と会社のあいだを 6 分あけ、断られたら 15 分休むようにした（lib/portal/report.ts）。
-- 22 社で 2 時間以上かかるので、始める時刻を早める。まとめは今までどおり遅くとも 07:55 に送る。
--
-- UTC 19〜22時 = 日本時間 04〜07時台
select cron.alter_job(
  (select jobid from cron.job where jobname = 'portal-sync-tick'),
  schedule := '*/2 19-22 * * *'
);
